/* ---------------------------------------------------------------------------
 * RGBA to YUV Conversion
 * --------------------------------------------------------------------------- */
static inline void rgba_to_yuv(uint8_t r, uint8_t g, uint8_t b,
                               uint8_t *y, uint8_t *u, uint8_t *v)
{
    int y_val = ((66 * r + 129 * g + 25 * b + 128) >> 8) + 16;
    int u_val = ((-38 * r - 74 * g + 112 * b + 128) >> 8) + 128;
    int v_val = ((112 * r - 94 * g - 18 * b + 128) >> 8) + 128;

    *y = (uint8_t)(y_val < 0 ? 0 : (y_val > 255 ? 255 : y_val));
    *u = (uint8_t)(u_val < 0 ? 0 : (u_val > 255 ? 255 : u_val));
    *v = (uint8_t)(v_val < 0 ? 0 : (v_val > 255 ? 255 : v_val));
}

/* ---------------------------------------------------------------------------
 * Drawing Primitives
 * --------------------------------------------------------------------------- */
static void blend_pixel(AVFrame *frame, int x, int y,
                        uint8_t r, uint8_t g, uint8_t b, uint8_t alpha)
{
    if (x < 0 || x >= frame->width || y < 0 || y >= frame->height || alpha == 0)
        return;

    int format = frame->format;
    if (format == AV_PIX_FMT_RGB24) {
        uint8_t *p = frame->data[0] + y * frame->linesize[0] + x * 3;
        p[0] = (uint8_t)((r * alpha + p[0] * (255 - alpha)) / 255);
        p[1] = (uint8_t)((g * alpha + p[1] * (255 - alpha)) / 255);
        p[2] = (uint8_t)((b * alpha + p[2] * (255 - alpha)) / 255);
    } else if (format == AV_PIX_FMT_RGBA) {
        uint8_t *p = frame->data[0] + y * frame->linesize[0] + x * 4;
        p[0] = (uint8_t)((r * alpha + p[0] * (255 - alpha)) / 255);
        p[1] = (uint8_t)((g * alpha + p[1] * (255 - alpha)) / 255);
        p[2] = (uint8_t)((b * alpha + p[2] * (255 - alpha)) / 255);
        p[3] = (uint8_t)(alpha + p[3] * (255 - alpha) / 255);
    } else if (format == AV_PIX_FMT_YUV420P) {
        uint8_t py, pu, pv;
        rgba_to_yuv(r, g, b, &py, &pu, &pv);

        uint8_t *y_ptr = frame->data[0] + y * frame->linesize[0] + x;
        *y_ptr = (uint8_t)((py * alpha + (*y_ptr) * (255 - alpha)) / 255);

        if ((x % 2 == 0) && (y % 2 == 0)) {
            int cx = x / 2;
            int cy = y / 2;
            uint8_t *u_ptr = frame->data[1] + cy * frame->linesize[1] + cx;
            uint8_t *v_ptr = frame->data[2] + cy * frame->linesize[2] + cx;
            *u_ptr = (uint8_t)((pu * alpha + (*u_ptr) * (255 - alpha)) / 255);
            *v_ptr = (uint8_t)((pv * alpha + (*v_ptr) * (255 - alpha)) / 255);
        }
    } else if (format == AV_PIX_FMT_NV12) {
        uint8_t py, pu, pv;
        rgba_to_yuv(r, g, b, &py, &pu, &pv);

        uint8_t *y_ptr = frame->data[0] + y * frame->linesize[0] + x;
        *y_ptr = (uint8_t)((py * alpha + (*y_ptr) * (255 - alpha)) / 255);

        if ((x % 2 == 0) && (y % 2 == 0)) {
            int cx = x & ~1;
            int cy = y / 2;
            uint8_t *uv_ptr = frame->data[1] + cy * frame->linesize[1] + cx;
            uv_ptr[0] = (uint8_t)((pu * alpha + uv_ptr[0] * (255 - alpha)) / 255);
            uv_ptr[1] = (uint8_t)((pv * alpha + uv_ptr[1] * (255 - alpha)) / 255);
        }
    }
}

static void draw_box_rect(AVFrame *frame, int rx, int ry, int rw, int rh, uint32_t color)
{
    uint8_t r = (uint8_t)((color >> 24) & 0xFF);
    uint8_t g = (uint8_t)((color >> 16) & 0xFF);
    uint8_t b = (uint8_t)((color >> 8) & 0xFF);
    uint8_t a = (uint8_t)(color & 0xFF);
    if (a == 0) return;

    int x1 = rx < 0 ? 0 : rx;
    int y1 = ry < 0 ? 0 : ry;
    int x2 = (rx + rw) > frame->width ? frame->width : (rx + rw);
    int y2 = (ry + rh) > frame->height ? frame->height : (ry + rh);

    for (int y = y1; y < y2; y++) {
        for (int x = x1; x < x2; x++) {
            blend_pixel(frame, x, y, r, g, b, a);
        }
    }
}

/* Render 8x16 fallback bitmap font */
static void draw_glyph_8x16(AVFrame *frame, int x, int y, char c,
                            int scale, uint8_t r, uint8_t g, uint8_t b, uint8_t a)
{
    if (c < 32 || c > 126) c = '?';
    const uint8_t *glyph = font8x16_basic[c - 32];

    for (int row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                for (int sy = 0; sy < scale; sy++) {
                    for (int sx = 0; sx < scale; sx++) {
                        blend_pixel(frame, x + col * scale + sx, y + row * scale + sy,
                                    r, g, b, a);
                    }
                }
            }
        }
    }
}

/* ---------------------------------------------------------------------------
 * Internal Configuration Structure
 * --------------------------------------------------------------------------- */
typedef struct {
    const char *text;
    const char *font_path;
    int font_size;
    int x;
    int y;
    uint32_t text_color;
    bool draw_box;
    uint32_t box_color;
    bool show_timecode;
    AVRational timecode_rate;
} zstr_text_overlay_config_t;

static zstr_text_overlay_t* zstr_text_overlay_create_internal(const zstr_text_overlay_config_t *cfg);

/* ---------------------------------------------------------------------------
 * Lifecycle & Initialization
 * --------------------------------------------------------------------------- */
zstr_text_overlay_t* zstr_text_overlay_alloc(const char *opt_string)
{
    zstr_text_overlay_config_t cfg = {
        .text = "",
        .font_path = NULL,
        .font_size = 32,
        .x = 20,
        .y = 20,
        .text_color = 0xFFFFFFFF,
        .draw_box = false,
        .box_color = 0x00000080,
        .show_timecode = false,
        .timecode_rate = (AVRational){30, 1}
    };

    if (opt_string && opt_string[0] != '\0') {
        char *copy = strdup(opt_string);
        if (copy) {
            char *tok = strtok(copy, ":,");
            while (tok) {
                char *eq = strchr(tok, '=');
                if (eq) {
                    *eq = '\0';
                    const char *k = tok;
                    const char *v = eq + 1;
                    if (strcmp(k, "text") == 0) {
                        cfg.text = v;
                    } else if (strcmp(k, "font_path") == 0 || strcmp(k, "fontfile") == 0) {
                        cfg.font_path = v;
                    } else if (strcmp(k, "font_size") == 0 || strcmp(k, "size") == 0) {
                        cfg.font_size = atoi(v);
                    } else if (strcmp(k, "x") == 0) {
                        cfg.x = atoi(v);
                    } else if (strcmp(k, "y") == 0) {
                        cfg.y = atoi(v);
                    } else if (strcmp(k, "color") == 0) {
                        cfg.text_color = (uint32_t)strtoul(v, NULL, 0);
                    } else if (strcmp(k, "box") == 0) {
                        cfg.draw_box = (atoi(v) != 0);
                    } else if (strcmp(k, "boxcolor") == 0) {
                        cfg.box_color = (uint32_t)strtoul(v, NULL, 0);
                    } else if (strcmp(k, "timecode") == 0) {
                        cfg.show_timecode = (atoi(v) != 0);
                    }
                }
                tok = strtok(NULL, ":,");
            }
            zstr_text_overlay_t *res = zstr_text_overlay_create_internal(&cfg);
            free(copy);
            return res;
        }
    }

    return zstr_text_overlay_create_internal(&cfg);
}

static zstr_text_overlay_t* zstr_text_overlay_create_internal(const zstr_text_overlay_config_t *cfg)
{
    zstr_text_overlay_t *s = calloc(1, sizeof(*s));
    if (!s) return NULL;

    pthread_mutex_init(&s->lock, NULL);

    if (cfg) {
        if (cfg->text) {
            strncpy(s->text, cfg->text, sizeof(s->text) - 1);
        }
        if (cfg->font_path) {
            strncpy(s->font_path, cfg->font_path, sizeof(s->font_path) - 1);
        }
        s->font_size = cfg->font_size > 0 ? cfg->font_size : 32;
        s->x = cfg->x;
        s->y = cfg->y;
        s->text_color = cfg->text_color ? cfg->text_color : 0xFFFFFFFF;
        s->draw_box = cfg->draw_box;
        s->box_color = cfg->box_color ? cfg->box_color : 0x00000080;
        s->show_timecode = cfg->show_timecode;
        s->timecode_rate = (cfg->timecode_rate.num > 0) ? cfg->timecode_rate : (AVRational){30, 1};
    } else {
        s->font_size = 32;
        s->x = 20;
        s->y = 20;
        s->text_color = 0xFFFFFFFF;
        s->timecode_rate = (AVRational){30, 1};
    }

#if HAVE_FREETYPE
    if (FT_Init_FreeType(&s->ft_lib) == 0) {
        const char *cand_fonts[] = {
            s->font_path[0] ? s->font_path : NULL,
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
            "/usr/share/fonts/dejavu/DejaVuSans.ttf",
            "/usr/share/fonts/truetype/freefont/FreeSans.ttf",
            "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"
        };
        for (size_t i = 0; i < sizeof(cand_fonts)/sizeof(cand_fonts[0]); i++) {
            if (cand_fonts[i] && FT_New_Face(s->ft_lib, cand_fonts[i], 0, &s->ft_face) == 0) {
                FT_Set_Pixel_Sizes(s->ft_face, 0, s->font_size);
                s->ft_ready = true;
                break;
            }
        }
    }
#endif

    return s;
}

int zstr_text_overlay_set_param(zstr_text_overlay_t *s, const char *param_str)
{
    if (!s || !param_str || param_str[0] == '\0') return AVERROR(EINVAL);
    char *copy = strdup(param_str);
    if (!copy) return AVERROR(ENOMEM);

    pthread_mutex_lock(&s->lock);
    char *tok = strtok(copy, ":,");
    while (tok) {
        char *eq = strchr(tok, '=');
        if (eq) {
            *eq = '\0';
            const char *k = tok;
            const char *v = eq + 1;

            if (strcmp(k, "text") == 0) {
                strncpy(s->text, v, sizeof(s->text) - 1);
                s->text[sizeof(s->text) - 1] = '\0';
            } else if (strcmp(k, "x") == 0) {
                s->x = atoi(v);
            } else if (strcmp(k, "y") == 0) {
                s->y = atoi(v);
            } else if (strcmp(k, "color") == 0) {
                s->text_color = (uint32_t)strtoul(v, NULL, 0);
            } else if (strcmp(k, "box") == 0) {
                s->draw_box = (atoi(v) != 0);
            } else if (strcmp(k, "boxcolor") == 0) {
                s->box_color = (uint32_t)strtoul(v, NULL, 0);
            } else if (strcmp(k, "timecode") == 0) {
                s->show_timecode = (atoi(v) != 0);
            } else if (strcmp(k, "font_size") == 0 || strcmp(k, "size") == 0) {
                s->font_size = atoi(v);
#if HAVE_FREETYPE
                if (s->ft_ready && s->font_size > 0) {
                    FT_Set_Pixel_Sizes(s->ft_face, 0, s->font_size);
                }
#endif
            }
        }
        tok = strtok(NULL, ":,");
    }
    pthread_mutex_unlock(&s->lock);
    free(copy);
    return 0;
}

int zstr_text_overlay_set_text(zstr_text_overlay_t *s, const char *text)
{
    if (!s) return AVERROR(EINVAL);
    pthread_mutex_lock(&s->lock);
    if (text) {
        strncpy(s->text, text, sizeof(s->text) - 1);
        s->text[sizeof(s->text) - 1] = '\0';
    } else {
        s->text[0] = '\0';
    }
    pthread_mutex_unlock(&s->lock);
    return 0;
}

int zstr_text_overlay_set_subtitle(zstr_text_overlay_t *s, const char *text,
                                  int64_t start_pts, int64_t duration_pts,
                                  AVRational time_base)
{
    if (!s) return AVERROR(EINVAL);
    pthread_mutex_lock(&s->lock);
    if (text) {
        strncpy(s->subtitle, text, sizeof(s->subtitle) - 1);
        s->subtitle[sizeof(s->subtitle) - 1] = '\0';
        s->subtitle_end_pts = start_pts + duration_pts;
        s->subtitle_tb = time_base;
    } else {
        s->subtitle[0] = '\0';
        s->subtitle_end_pts = 0;
    }
    pthread_mutex_unlock(&s->lock);
    return 0;
}

void zstr_text_overlay_set_position(zstr_text_overlay_t *s, int x, int y)
{
    if (!s) return;
    pthread_mutex_lock(&s->lock);
    s->x = x;
    s->y = y;
    pthread_mutex_unlock(&s->lock);
}

void zstr_text_overlay_enable_timecode(zstr_text_overlay_t *s, bool enable)
{
    if (!s) return;
    pthread_mutex_lock(&s->lock);
    s->show_timecode = enable;
    pthread_mutex_unlock(&s->lock);
}

/* ---------------------------------------------------------------------------
 * Core Processing & Rendering
 * --------------------------------------------------------------------------- */
int zstr_text_overlay_process(zstr_text_overlay_t *s, const AVFrame *in, AVFrame *out)
{
    if (!s || !in || !out) return AVERROR(EINVAL);

    /* Validate supported pixel formats */
    if (in->format != AV_PIX_FMT_YUV420P &&
        in->format != AV_PIX_FMT_NV12 &&
        in->format != AV_PIX_FMT_RGB24 &&
        in->format != AV_PIX_FMT_RGBA)
    {
        /* Unsupported pixel format: copy or passthrough */
        if (out != in) {
            av_frame_ref(out, (AVFrame*)in);
        }
        return 0;
    }

    /* Allocate or prepare destination frame */
    if (out != in) {
        out->format = in->format;
        out->width = in->width;
        out->height = in->height;
        int ret = av_frame_copy_props(out, in);
        if (ret < 0) return ret;

        ret = av_frame_get_buffer(out, 64);
        if (ret < 0) return ret;

        ret = av_image_copy_to_buffer(out->data[0], av_image_get_buffer_size(in->format, in->width, in->height, 64),
                                      (const uint8_t * const*)in->data, in->linesize,
                                      in->format, in->width, in->height, 64);
        /* Alternative: use av_image_copy */
        av_image_copy(out->data, out->linesize, (const uint8_t * const*)in->data,
                      in->linesize, in->format, in->width, in->height);
    } else {
        int ret = av_frame_make_writable(out);
        if (ret < 0) return ret;
    }

    pthread_mutex_lock(&s->lock);

    /* Determine text to render */
    char buf[512] = {0};
    const char *render_text = s->text;

    if (s->show_timecode) {
        int64_t pts = in->pts;
        if (pts == AV_NOPTS_VALUE) {
            pts = (int64_t)s->frame_index * 1000 / (s->timecode_rate.num ? s->timecode_rate.num : 30);
        }
        uint64_t ms = (uint64_t)(pts >= 0 ? pts : 0);
        /* If time_base is available, convert to ms */
        if (in->time_base.den > 0 && in->time_base.num > 0) {
            ms = (uint64_t)av_rescale_q(pts, in->time_base, (AVRational){1, 1000});
        }
        unsigned hh = (unsigned)(ms / 3600000ULL);
        unsigned mm = (unsigned)((ms / 60000ULL) % 60ULL);
        unsigned ss = (unsigned)((ms / 1000ULL) % 60ULL);
        unsigned msec = (unsigned)(ms % 1000ULL);

        snprintf(buf, sizeof(buf), "Frame: %" PRIu64 "  TC: %02u:%02u:%02u.%03u",
                 s->frame_index, hh, mm, ss, msec);
        render_text = buf;
    } else if (s->subtitle[0] != '\0') {
        int64_t cur_pts = in->pts;
        if (s->subtitle_tb.den > 0 && in->time_base.den > 0) {
            cur_pts = av_rescale_q(cur_pts, in->time_base, s->subtitle_tb);
        }
        if (cur_pts <= s->subtitle_end_pts) {
            render_text = s->subtitle;
        } else {
            s->subtitle[0] = '\0';
            s->subtitle_end_pts = 0;
        }
    }

    s->frame_index++;

    if (!render_text || render_text[0] == '\0') {
        pthread_mutex_unlock(&s->lock);
        return 0;
    }

    /* Unpack text & box colors */
    uint8_t tr = (uint8_t)((s->text_color >> 24) & 0xFF);
    uint8_t tg = (uint8_t)((s->text_color >> 16) & 0xFF);
    uint8_t tb = (uint8_t)((s->text_color >> 8) & 0xFF);
    uint8_t ta = (uint8_t)(s->text_color & 0xFF);

    int cur_x = s->x;
    int cur_y = s->y;
    int text_len = (int)strlen(render_text);

#if HAVE_FREETYPE
    if (s->ft_ready && s->ft_face) {
        /* Calculate text dimensions for optional box */
        int total_w = 0;
        for (int i = 0; i < text_len; i++) {
            if (FT_Load_Char(s->ft_face, render_text[i], FT_LOAD_DEFAULT) == 0) {
                total_w += (s->ft_face->glyph->advance.x >> 6);
            }
        }
        int line_h = s->font_size > 0 ? s->font_size : 32;

        if (s->draw_box) {
            draw_box_rect(out, cur_x - 4, cur_y - 4, total_w + 8, line_h + 8, s->box_color);
        }

        /* Render FreeType glyphs */
        int pen_x = cur_x;
        int pen_y = cur_y + line_h - 4; /* baseline */

        for (int i = 0; i < text_len; i++) {
            char ch = render_text[i];
            if (ch == '\n') {
                pen_x = cur_x;
                pen_y += line_h;
                continue;
            }
            if (FT_Load_Char(s->ft_face, ch, FT_LOAD_RENDER) == 0) {
                FT_Bitmap *bmp = &s->ft_face->glyph->bitmap;
                int gx = pen_x + s->ft_face->glyph->bitmap_left;
                int gy = pen_y - s->ft_face->glyph->bitmap_top;

                for (unsigned int r = 0; r < bmp->rows; r++) {
                    for (unsigned int c = 0; c < bmp->width; c++) {
                        uint8_t glyph_alpha = bmp->buffer[r * bmp->width + c];
                        if (glyph_alpha > 0) {
                            uint8_t combined_alpha = (uint8_t)((glyph_alpha * ta) / 255);
                            blend_pixel(out, gx + c, gy + r, tr, tg, tb, combined_alpha);
                        }
                    }
                }
                pen_x += (s->ft_face->glyph->advance.x >> 6);
            }
        }

        pthread_mutex_unlock(&s->lock);
        return 0;
    }
#endif

    /* Fallback: 8x16 Bitmap Font */
    int scale = s->font_size / 16;
    if (scale < 1) scale = 1;

    int total_w = text_len * 8 * scale;
    int total_h = 16 * scale;

    if (s->draw_box) {
        draw_box_rect(out, cur_x - 4, cur_y - 4, total_w + 8, total_h + 8, s->box_color);
    }

    int px = cur_x;
    int py = cur_y;
    for (int i = 0; i < text_len; i++) {
        char ch = render_text[i];
        if (ch == '\n') {
            px = cur_x;
            py += 16 * scale;
            continue;
        }
        draw_glyph_8x16(out, px, py, ch, scale, tr, tg, tb, ta);
        px += 8 * scale;
    }

    pthread_mutex_unlock(&s->lock);
    return 0;
}

void zstr_text_overlay_free(zstr_text_overlay_t **ps)
{
    if (!ps || !*ps) return;
    zstr_text_overlay_t *s = *ps;

#if HAVE_FREETYPE
    if (s->ft_ready) {
        if (s->ft_face) {
            FT_Done_Face(s->ft_face);
            s->ft_face = NULL;
        }
        if (s->ft_lib) {
            FT_Done_FreeType(s->ft_lib);
            s->ft_lib = NULL;
        }
        s->ft_ready = false;
    }
#endif

    pthread_mutex_destroy(&s->lock);
    free(s);
    *ps = NULL;
}
